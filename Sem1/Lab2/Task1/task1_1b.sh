# Копирование содержимого одного файла в другой (1.1 вариант 2: while)
if [ $# -ne 2 ]; then
  echo "Использование: $0 <исходный_файл> <целевой_файл>"
  exit 1
fi
if [ ! -f "$1" ] || [ ! -f "$2" ]; then
  echo "Оба файла должны существовать до операции."
  exit 1
fi
> "$2"
while IFS= read -r line; do
  echo "$line" >> "$2"
done < "$1"
echo "Содержимое $1 скопировано в $2"


